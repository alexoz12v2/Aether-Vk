#!/usr/bin/env python3
"""Generates the comet dust phase-function LUT shared by Rust and GLSL.

Source: the Lowell Observatory composite dust phase function (D. Schleicher, 2010 May): the
Halley curve of Schleicher et al. 1998 (Icarus 132, 397) at small phase angles spliced to the
Marcus 2007 (ICQ) Henyey-Greenstein fit (g_f = 0.9, g_b = -0.6, k = 0.95) at mid and large angles,
tabulated at 1 degree from 0 to 180 and normalised to 1 at 0 degrees.
  https://asteroid.lowell.edu/comet/dustphase/   (table: /static/comet/dustphaseHM_table.txt)
The saved copy lives in assets/sim/data/dustphaseHM_table.txt. This script writes
aethervk.core/rlib/src/scene/dust/phase.rs (the whole file) and replaces the block between the
// PHASE-LUT-BEGIN / // PHASE-LUT-END markers of assets/sim/dust_common.glsl.
usage: gen_phase_lut.py [table.txt]
"""
import re
import sys
from pathlib import Path

root = Path(__file__).resolve().parent.parent
table = Path(sys.argv[1]) if len(sys.argv) > 1 else root / "assets/sim/data/dustphaseHM_table.txt"
rows = []
for line in table.read_text().splitlines():
    m = re.match(r"^\s*(\d+)\.0\s+([0-9.]+)\s+([0-9.]+)\s*$", line)
    if m:
        rows.append((int(m.group(1)), m.group(2), m.group(3)))
assert [r[0] for r in rows] == list(range(181)), "expected 181 rows 0..180"
assert rows[0][1] == "1.0000" and rows[90][2] == "1.0000"
vals = [r[1] for r in rows]

rs = root / "aethervk.core/rlib/src/scene/dust/phase.rs"
lines = ["//! Comet dust phase function Φ(α): the Lowell Observatory composite (D. Schleicher, 2010 May),",
         "//! the Halley curve of Schleicher et al. 1998 (Icarus 132, 397) at small phase angles spliced to",
         "//! the Marcus 2007 (ICQ) Henyey–Greenstein fit (g_f = 0.9, g_b = −0.6, k = 0.95) at mid and large",
         "//! angles, tabulated at 1° from 0° to 180° and normalised to Φ(0) = 1. Source:",
         "//! <https://asteroid.lowell.edu/comet/dustphase/> (`/static/comet/dustphaseHM_table.txt`, saved as",
         "//! `assets/sim/data/dustphaseHM_table.txt`). Generated by `scripts/gen_phase_lut.py`; the GLSL",
         "//! mirror `DUST_PHASE_HM` in `assets/sim/dust_common.glsl` is written by the same script and",
         "//! checked bit for bit by `phase_lut_matches_glsl`. Do not edit by hand.",
         "",
         "/// Φ(α) at integer degrees 0..=180, Φ(0) = 1 (0.5375 at 90°, 1231.17 at 180°: forward scattering).",
         "pub const PHASE_HM_0DEG: [f32; 181] = ["]
for i in range(0, 181, 6):
    lines.append("  " + " ".join(f"{v}," for v in vals[i:i + 6]))
lines.append("];")
lines.append("")
lines.append("/// Φ(α) for a phase angle in radians (clamped to 0..π), linear between the table's degrees.")
lines.append("/// Mirror of `dust_phase_function`.")
lines.append("pub fn phase_function(alpha_rad: f32) -> f32 {")
lines.append("  let deg = (alpha_rad * (180.0 / core::f32::consts::PI)).clamp(0.0, 180.0);")
lines.append("  let i = (deg as usize).min(179);")
lines.append("  let f = deg - i as f32;")
lines.append("  PHASE_HM_0DEG[i] + (PHASE_HM_0DEG[i + 1] - PHASE_HM_0DEG[i]) * f")
lines.append("}")
lines.append("")
lines.append("/// The radiance weight of a packet, `p · Φ(α) / r_h²` (r_h in AU): its optical depth times this is")
lines.append("/// the radiance factor I/F the pixel shows (the composite's white point is then a radiance factor,")
lines.append("/// `white_to_mag_arcsec2`). `sun_dir` is the unit direction from the packet to the Sun and `to_eye`")
lines.append("/// the vector from the packet to the eye (any length; a zero length counts as α = 0), both in the")
lines.append("/// same axes. Mirror of `dust_radiance_weight`.")
lines.append("pub fn radiance_weight(albedo: f32, sun_dir: [f32; 3], to_eye: [f32; 3], r_h_au: f32) -> f32 {")
lines.append("  let n = to_eye[0] * to_eye[0] + to_eye[1] * to_eye[1] + to_eye[2] * to_eye[2];")
lines.append("  let cos_a = if n > 0.0 {")
lines.append("    (sun_dir[0] * to_eye[0] + sun_dir[1] * to_eye[1] + sun_dir[2] * to_eye[2])")
lines.append("      / aethervk_oshal_rlib::math::FloatLike::sqrt(n)")
lines.append("  } else {")
lines.append("    1.0")
lines.append("  };")
lines.append("  let alpha = aethervk_oshal_rlib::math::FloatLike::acos(cos_a.clamp(-1.0, 1.0));")
lines.append("  let r = r_h_au.max(1e-6);")
lines.append("  albedo * phase_function(alpha) / (r * r)")
lines.append("}")
lines.append("")
rs.write_text("\n".join(lines))

glsl = root / "assets/sim/dust_common.glsl"
src = glsl.read_text()
block = ["// PHASE-LUT-BEGIN (generated by scripts/gen_phase_lut.py; the 181 values of",
         "// assets/sim/data/dustphaseHM_table.txt, the Lowell composite dust phase function, Schleicher 2010,",
         "// normalised to 1 at 0 degrees, are dust::phase::PHASE_HM_0DEG and travel in the pyramid header at",
         "// DUST_PYR_PHASE_LUT: a const float[181] in the shader with a dynamic index changed the splat's",
         "// results on the GPU even when unused. Do not edit by hand.)",
         "// Phi(alpha) for a phase angle in radians (clamped to 0..pi), linear between the table's degrees",
         "// (dust::phase::phase_function)",
         "float dust_phase_function(DustUintBuffer pyr, float alphaRad) {",
         "    float deg = clamp(alphaRad * (180.0 / DUST_PI_F32), 0.0, 180.0);",
         "    uint i = min(uint(deg), 179u);",
         "    float f = deg - float(i);",
         "    float a = uintBitsToFloat(pyr.v[DUST_PYR_PHASE_LUT + i]);",
         "    float b = uintBitsToFloat(pyr.v[DUST_PYR_PHASE_LUT + i + 1u]);",
         "    return a + (b - a) * f;",
         "}",
         "// PHASE-LUT-END"]
text = "\n".join(block)
if "// PHASE-LUT-BEGIN" in src:
    src = re.sub(r"// PHASE-LUT-BEGIN.*?// PHASE-LUT-END", text, src, flags=re.S)
else:
    anchor = "// ─── Flow (mirror of dust::flow_*)"
    assert anchor in src
    src = src.replace(anchor, text + "\n\n" + anchor)
glsl.write_text(src)
print(f"wrote {rs} and the GLSL block ({len(vals)} values)")
