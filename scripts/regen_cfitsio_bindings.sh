#!/usr/bin/env bash
# Regenerates aethervk.cfitsio/sys/src/bindings.rs (committed bindgen output) from the cfitsio
# headers that aethervk.cfitsio/sys/build.rs installed. Run on the Linux dev box after
#   cargo build -p aethervk-cfitsio-sys
# Override the include directory with AETHERVK_CFITSIO_INCLUDE=<dir> (e.g. $AETHERVK_CFITSIO_DIR/include).
#
# cfitsio is built with its `bzip2` feature, so bzlib.h sits next to fitsio.h.
# One file serves every target: the allowlisted prototypes use only int/long/long long/double/
# float/size_t/pointers (mapped through core::ffi at compile time); FITSfile is opaque; no layout
# tests (the sys crate's unit test checks the fitsfile size on the host instead).
set -euo pipefail

BINDGEN_VERSION=0.72.1
LIBCLANG_PATH="${LIBCLANG_PATH:-/usr/lib/llvm-18/lib}"
REPO="$(cd "$(dirname "$0")/.." && pwd)"
SYS="$REPO/aethervk.cfitsio/sys"
OUT="$SYS/src/bindings.rs"

INC="${AETHERVK_CFITSIO_INCLUDE:-}"
if [ -z "$INC" ]; then
  # both cargo layouts: target/debug/build/<pkg>-<hash>/out and target/debug/build/<pkg>/<hash>/out
  INC="$(find "$REPO/target/debug/build" -maxdepth 7 -type d -path '*aethervk-cfitsio-sys*/out/vcpkg_installed/*/include' 2>/dev/null | head -1 || true)"
fi
if [ -z "$INC" ] || [ ! -f "$INC/fitsio.h" ]; then
  echo "no fitsio.h found; run 'cargo build -p aethervk-cfitsio-sys' first or set AETHERVK_CFITSIO_INCLUDE" >&2
  exit 1
fi
echo "include dir: $INC"

BINDGEN="$(command -v bindgen || true)"
[ -n "$BINDGEN" ] || BINDGEN="${CARGO_HOME:-$HOME/.cargo}/bin/bindgen"
if [ ! -x "$BINDGEN" ] || [ "$("$BINDGEN" --version | awk '{print $2}')" != "$BINDGEN_VERSION" ]; then
  cargo install bindgen-cli --version "$BINDGEN_VERSION" --locked
  BINDGEN="${CARGO_HOME:-$HOME/.cargo}/bin/bindgen"
fi

LIBCLANG_PATH="$LIBCLANG_PATH" "$BINDGEN" "$SYS/wrapper.h" -o "$OUT" \
  --use-core --ctypes-prefix core::ffi --no-layout-tests --no-doc-comments --rust-target 1.85 \
  --raw-line '// generated by scripts/regen_cfitsio_bindings.sh from cfitsio 4.7.0; do not edit' \
  --raw-line '/// Opaque: the real struct holds off_t/long fields whose layout differs per OS.' \
  --raw-line 'pub enum FITSfile {}' \
  --blocklist-type 'FITSfile' --blocklist-type '(__)?off_t|OFF_T' \
  --allowlist-function '^ff(omem|imem|clos|delt|mahd|mrhd|ghdn|thdu|ghdt|gipr|giprll|gidt|gidm|giszll|ghsp|grec|gcrd|gkey|gkls|gkyd|gkyj|gkyjj|gkys|gpve|gpvd|s2dt|s2tm|gerr|gmsg|cmsg|vers|crim|crimll|ppr|ppre|ppri|pcks|hdr2str|cnvthdr2str|pky|pkyj|pkyd|pkys|pkyl|pkls|plsw|pcom|phis|prec|dkey|crtb|pcl|pnul|pscl|phprll|ghadll)$' \
  --allowlist-function '^fits_(is_reentrant|is_compressed_image|set_compression_type|set_tile_dim|set_hcomp_scale|set_hcomp_smooth|set_quantize_level|set_quantize_method|set_quantize_dither|set_dither_seed|set_lossy_int)$' \
  --allowlist-function '^(fffree|uncompress2mem_from_mem|compress2mem_from_mem|BZ2_bzBuffToBuffDecompress|BZ2_bzBuffToBuffCompress)$' \
  --allowlist-var '^BZ_(OK|RUN_OK|STREAM_END|MEM_ERROR|DATA_ERROR|DATA_ERROR_MAGIC|UNEXPECTED_EOF|OUTBUFF_FULL)$' \
  --allowlist-var '^(READONLY|READWRITE|IMAGE_HDU|ASCII_TBL|BINARY_TBL|ANY_HDU|TBYTE|TSBYTE|TSHORT|TUSHORT|TINT|TUINT|TLONG|TULONG|TLONGLONG|TULONGLONG|TFLOAT|TDOUBLE|TSTRING|TLOGICAL|BYTE_IMG|SBYTE_IMG|SHORT_IMG|USHORT_IMG|LONG_IMG|ULONG_IMG|LONGLONG_IMG|ULONGLONG_IMG|FLOAT_IMG|DOUBLE_IMG|FLEN_[A-Z]+|BAD_DATE|END_OF_FILE|READ_ERROR|WRITE_ERROR|KEY_NO_EXIST|NOT_IMAGE|BAD_BITPIX|BAD_NAXIS|VALUE_UNDEFINED|NUM_OVERFLOW|MEMORY_ALLOCATION|DATA_COMPRESSION_ERR|DATA_DECOMPRESSION_ERR|RICE_1|GZIP_1|GZIP_2|PLIO_1|HCOMPRESS_1|NOCOMPRESS|NO_DITHER|SUBTRACTIVE_DITHER_1|SUBTRACTIVE_DITHER_2)$' \
  -- -I"$INC" -DCFITSIO_STATIC_DEFINE=1

echo "wrote $OUT"
sha256sum "$OUT"
