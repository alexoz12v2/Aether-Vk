// ============================================================================

/// Represents a dust particle that has an age (in milliseconds)
#[derive(Debug, Clone, Copy)]
pub struct TemporalParticle {
  pub position: Vec3f32,
  pub age_ms: f32,
}

/// Clusters particles into age buckets and extracts a single, robust Center of Mass
/// for each bucket by rejecting statistical outliers (Z-Score filtering).
pub fn compute_robust_centroids(
  particles: &[TemporalParticle],
  bucket_size_ms: f32,
  z_score_threshold: f32,
) -> Vec<Vec3f32> {
  if particles.is_empty() {
    return Vec::new();
  }

  // Determine the max age to know how many buckets we need
  let max_age = particles.iter().fold(0.0f32, |acc, p| acc.max(p.age_ms));
  let num_buckets = (max_age / bucket_size_ms).ceil() as usize + 1;

  let mut buckets: Vec<Vec<Vec3f32>> = alloc::vec![Vec::new(); num_buckets];

  // 1. Group by age
  for p in particles {
    let bucket_idx = (p.age_ms / bucket_size_ms) as usize;
    buckets[bucket_idx].push(p.position);
  }

  let mut centroids = Vec::new();

  // 2. Process each bucket
  for bucket in buckets {
    if bucket.is_empty() {
      continue;
    }

    // Compute Mean (\mu)
    let mut mean = Vec3f32::zero();
    for &pos in &bucket {
      mean += pos;
    }
    mean /= bucket.len() as f32;

    // Compute Standard Deviation (\sigma)
    let mut variance = 0.0;
    for &pos in &bucket {
      variance += (pos - mean).length_squared();
    }
    let std_dev = (variance / bucket.len() as f32).sqrt();

    // 3. Outlier Rejection & Refined CoM
    let mut refined_mean = Vec3f32::zero();
    let mut inlier_count = 0;

    for &pos in &bucket {
      let dist = (pos - mean).length();

      // Z-Score = Distance / StdDev
      // If the particle is within `z_score_threshold` standard deviations, it's an inlier
      if std_dev < 1e-5 || (dist / std_dev) <= z_score_threshold {
        refined_mean += pos;
        inlier_count += 1;
      }
    }

    if inlier_count > 0 {
      refined_mean /= inlier_count as f32;
      centroids.push(refined_mean);
    }
  }

  centroids
}

