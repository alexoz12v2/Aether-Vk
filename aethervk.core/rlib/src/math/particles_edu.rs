/// Represents a Rational Cubic Bezier Segment.
#[derive(Debug, Clone, Copy)]
pub struct CubicBezier {
  pub p0: Vec3f32,
  pub p1: Vec3f32,
  pub p2: Vec3f32,
  pub p3: Vec3f32,
}

impl CubicBezier {
  /// Evaluates the curve at parametric value t [0, 1]
  pub fn evaluate(&self, t: f32) -> Vec3f32 {
    let mt = 1.0 - t;
    let mt2 = mt * mt;
    let mt3 = mt2 * mt;
    let t2 = t * t;
    let t3 = t2 * t;

    self.p0 * mt3 + self.p1 * (3.0 * mt2 * t) + self.p2 * (3.0 * mt * t2) + self.p3 * t3
  }
}

/// Converts a sequence of robust centroids into a contiguous sequence of smooth Cubic Bezier curves
/// using the Centripetal Catmull-Rom spline formulation.
pub fn generate_bezier_trajectory(centroids: &[Vec3f32]) -> Vec<CubicBezier> {
  if centroids.len() < 2 {
    return Vec::new();
  }

  let mut beziers = Vec::with_capacity(centroids.len() - 1);

  for i in 0..(centroids.len() - 1) {
    // To build a Catmull-Rom segment between P_i and P_{i+1}, we need P_{i-1} and P_{i+2}.
    // We handle boundaries by duplicating endpoints (extrapolating velocity to zero).
    let p_prev = if i == 0 {
      centroids[0]
    } else {
      centroids[i - 1]
    };
    let p_curr = centroids[i];
    let p_next = centroids[i + 1];
    let p_next_next = if i + 2 >= centroids.len() {
      centroids[i + 1]
    } else {
      centroids[i + 2]
    };

    // Standard Catmull-Rom to Bezier matrix conversion:
    // B0 = P_i
    // B1 = P_i + (P_{i+1} - P_{i-1}) / 6
    // B2 = P_{i+1} - (P_{i+2} - P_i) / 6
    // B3 = P_{i+1}

    let b0 = p_curr;
    let b1 = p_curr + (p_next - p_prev) * (1.0 / 6.0);
    let b2 = p_next - (p_next_next - p_curr) * (1.0 / 6.0);
    let b3 = p_next;

    beziers.push(CubicBezier {
      p0: b0,
      p1: b1,
      p2: b2,
      p3: b3,
    });
  }

  beziers
}
