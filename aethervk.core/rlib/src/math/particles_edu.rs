/// Represents a basic RGBA texture stored in host/device memory.
pub struct TextureRGBA {
  pub width: usize,
  pub height: usize,
  pub data: Vec<[f32; 4]>,
}

impl TextureRGBA {
  /// Bilinear interpolation to sample a color exactly at the UV coordinates
  /// generated by the `Distribution2D` (which is based on the Alpha channel).
  pub fn sample_bilinear(&self, u: f32, v: f32) -> [f32; 4] {
    let u = u.clamp(0.0, 1.0) * (self.width as f32 - 1.0);
    let v = v.clamp(0.0, 1.0) * (self.height as f32 - 1.0);

    let x0 = (u.floor() as usize).min(self.width - 1);
    let y0 = (v.floor() as usize).min(self.height - 1);
    let x1 = (x0 + 1).min(self.width - 1);
    let y1 = (y0 + 1).min(self.height - 1);

    let tx = u - x0 as f32;
    let ty = v - y0 as f32;

    let c00 = self.data[y0 * self.width + x0];
    let c10 = self.data[y0 * self.width + x1];
    let c01 = self.data[y1 * self.width + x0];
    let c11 = self.data[y1 * self.width + x1];

    let mut result = [0.0; 4];
    for i in 0..4 {
      let top = c00[i] * (1.0 - tx) + c10[i] * tx;
      let bottom = c01[i] * (1.0 - tx) + c11[i] * tx;
      result[i] = top * (1.0 - ty) + bottom * ty;
    }
    result
  }
}

